#!/bin/sh
# Rebuilds src/BridgeDex.inc from java/ (needs a JDK and the Android SDK).
#   ANDROID_HOME=... JAVA_HOME=... tools/build_dex.sh
set -e
cd "$(dirname "$0")/.."
JAR="$ANDROID_HOME/platforms/android-35/android.jar"
D8="$(ls -d "$ANDROID_HOME"/build-tools/* | sort | tail -1)/d8"
OUT=build/dex
rm -rf "$OUT" && mkdir -p "$OUT/classes"
"$JAVA_HOME/bin/javac" --release 8 -nowarn -cp "$JAR" -d "$OUT/classes" $(find java -name '*.java')
"$D8" --release --min-api 28 --lib "$JAR" --output "$OUT" $(find "$OUT/classes" -name '*.class')
{
  echo "// Generated by tools/build_dex.sh from java/ — do not edit."
  echo "static const unsigned char kBridgeDex[] = {"
  od -An -v -tx1 "$OUT/classes.dex" | sed 's/  */ /g; s/^ //; s/ $//; s/\([0-9a-f][0-9a-f]\)/0x\1,/g'
  echo "};"
} > src/BridgeDex.inc
echo "wrote src/BridgeDex.inc ($(wc -c < "$OUT/classes.dex") bytes of dex)"
